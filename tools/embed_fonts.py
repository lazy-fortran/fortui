#!/usr/bin/env python3
"""Regenerate the bundled FortUI fonts and their embedded C source.

Usage: python3 tools/embed_fonts.py [--subset SRC_DIR]

--subset re-creates assets/fonts/*-fortui.ttf from upstream DejaVu Sans TTFs in
SRC_DIR with pyftsubset (fontTools) using the code point set below. Without it,
only src/c/fortui_fonts.c is regenerated from the committed subset files.
DejaVu fonts: see assets/fonts/LICENSE-DejaVu (Bitstream Vera/Arev derived).
"""
import hashlib
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UNICODES = ("U+0020-007E,U+00A0-017F,U+0370-03FF,U+2000-206F,U+20AC,"
            "U+2190-21FF,U+2200-22FF,U+FFFD")
FONTS = [("DejaVuSans.ttf", "DejaVuSans-fortui.ttf", "regular"),
         ("DejaVuSans-Bold.ttf", "DejaVuSans-Bold-fortui.ttf", "bold")]


def main():
    out_dir = ROOT / "assets" / "fonts"
    if len(sys.argv) == 3 and sys.argv[1] == "--subset":
        for src, dst, _ in FONTS:
            subprocess.run(["pyftsubset", str(pathlib.Path(sys.argv[2]) / src),
                            "--unicodes=" + UNICODES, "--layout-features=",
                            "--no-hinting", "--output-file=" + str(out_dir / dst)],
                           check=True)
    lines = ["/* Generated by tools/embed_fonts.py; do not edit.",
             " * Code points: " + UNICODES]
    for _, dst, _ in FONTS:
        data = (out_dir / dst).read_bytes()
        lines.append(" * %s sha256 %s" % (dst, hashlib.sha256(data).hexdigest()))
    lines += [" * License: assets/fonts/LICENSE-DejaVu */", ""]
    for _, dst, name in FONTS:
        data = (out_dir / dst).read_bytes()
        lines.append("static const unsigned char font_%s[%d] = {" % (name, len(data)))
        for i in range(0, len(data), 20):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
        lines += ["};", ""]
    lines += [
        "/* Bundled TTF bytes for style 1 (regular) or 2 (bold). */",
        "const unsigned char *fortui_font_data(int style, int *size)",
        "{",
        "    if (style == 2) { *size = (int)sizeof(font_bold); return font_bold; }",
        "    *size = (int)sizeof(font_regular);",
        "    return font_regular;",
        "}",
        ""]
    (ROOT / "src" / "c" / "fortui_fonts.c").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
