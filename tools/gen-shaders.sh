#!/bin/sh
# Regenerate src/fortui_sdl_shaders.f90: the SPIR-V of shaders/*.{vert,frag},
# compiled with glslc (shaderc), as Fortran byte arrays for the SDL GPU backend.
set -eu
top=$(cd "$(dirname "$0")/.." && pwd)
out=$top/src/fortui_sdl_shaders.f90
tmp=$(mktemp -d "${TMPDIR:-/tmp}/fortui-shaders-XXXXXX")
trap 'rm -rf "$tmp"' EXIT
{
    echo "module fortui_sdl_shaders"
    echo "    !! SPIR-V of the SDL GPU shaders. Generated by tools/gen-shaders.sh from"
    echo "    !! shaders/ with $(glslc --version | head -1 | cut -d' ' -f1-2); do not edit."
    echo "    use iso_fortran_env, only: int8"
    echo "    implicit none"
    echo "    private"
    for s in shape.vert shape.frag textured.vert textured.frag; do
        name=$(echo "$s" | tr . _)
        glslc -O --target-env=vulkan1.0 "$top/shaders/$s" -o "$tmp/$name.spv"
        n=$(wc -c < "$tmp/$name.spv")
        echo "    integer(int8), parameter, public :: ${name}_spv($n) = int([ &"
        od -An -v -td1 "$tmp/$name.spv" | tr -s ' \n' '\n' | sed '/^$/d' | awk -v n="$n" '
            { printf "%s%s", (NR % 20 == 1 ? "        " : ""), $1
              if (NR < n) printf ","
              if (NR % 20 == 0 || NR == n) printf " &\n" }'
        echo "        ], int8)"
    done
    echo "end module fortui_sdl_shaders"
} > "$out"
